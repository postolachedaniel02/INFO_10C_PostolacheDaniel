a=5
b=4
print('suma ', a, '+', b,'=',a+b, end='\n')
print('produsul ', a, '*', b,'=',a*b, end='\n')
print('diferenta ', a, '-', b,'=',a-b, end='\n')
print('puterea ', a, '**', b, '=', a**b, end='\n')
print('câtul împărțirii ', a, '//', b, '=', a//b, end='\n')
print('restul împărțirii ', a, '%', b, '=', a%b, end='\n')